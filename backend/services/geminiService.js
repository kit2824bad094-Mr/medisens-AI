export async function detectRedFlags(text = "") {
  const matches = RED_FLAG_RULES.filter((rule) =>
    rule.match.every((regex) => regex.test(text))
  ).map((rule) => rule.flag);

  if (genAI && text.length > 20) {
    try {
      const model = genAI.getGenerativeModel({ model: "gemini-1.5-flash" });
      const prompt = `Analyze this patient intake transcript for urgent medical red flags requiring immediate physician triage:
"${text}"
Known critical symptoms: Acute chest pain radiating to arm/jaw, acute dyspnea, severe uncontrolled hypertension, sudden loss of consciousness, internal bleeding.
If there are red flags, return a JSON array of objects with: title, trigger, recommendation.
If no red flags, return an empty JSON array [].
Return ONLY raw JSON, no markdown fences.`;

      const result = await model.generateContent(prompt);
      const raw = result.response.text().trim().replace(/^```json\s*/i, "").replace(/```$/i, "");
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    } catch (err) {
      console.warn("[GeminiService] Red flag LLM analysis fallback:", err.message);
    }
  }

  return matches;
}

export async function generateClinicalSummary(patientInfo = {}, symptoms = [], reports = []) {
  const rawText = [
    ...symptoms.map((s) => s.answer),
    ...reports.flatMap((r) => r.fields.map((f) => `${f.label}: ${f.value}`)),
  ].join(" | ");

  const redFlags = await detectRedFlags(rawText);

  // Check measurements: Never invent measurements!
  const measurementAnswers = symptoms.filter((s) =>
    /pressure|sugar|glucose|temperature|bp|spo2/i.test(s.question)
  );

  const sanitizedMeasurements = measurementAnswers.map((m) => ({
    label: /pressure|bp/i.test(m.question) ? "Blood Pressure" : "Blood Sugar",
    status: sanitizeMeasurement(m.answer, /pressure|bp/i.test(m.question) ? "Blood Pressure" : "Blood Sugar"),
  }));

  if (genAI && symptoms.length > 0) {
    try {
      const model = genAI.getGenerativeModel({ model: "gemini-1.5-flash" });
      const prompt = `You are a clinical summarization engine for hospital outpatient intake.
SAFETY MANDATE:
1. NEVER invent or hallucinate vital signs or measurements (BP, sugar, heart rate, temp).
2. If unknown or not provided, record as "Not Available".
Patient: ${patientInfo.name}, ${patientInfo.age}y, ${patientInfo.sex}.
Patient Q&A:
${symptoms.map((s) => `- ${s.question}: ${s.answer}`).join("\n")}
Uploaded Reports:
${reports.map((r) => `- ${r.title} (${r.kind}): ${r.fields.map((f) => `${f.label}=${f.value}`).join(", ")}`).join("\n")}

Generate a structured clinical intake summary for the physician to review.
Return ONLY raw JSON with:
{
  "chiefComplaint": "string",
  "associatedSymptoms": ["string"],
  "duration": "string",
  "pastHistory": ["string"],
  "currentMedication": ["string"],
  "measurements": { "bp": "string", "glucose": "string" },
  "oneLiner": "string (e.g. 58M — chest heaviness for 1 day radiating to arm)",
  "urgency": "normal" | "priority" | "red-flag"
}`;

      const res = await model.generateContent(prompt);
      const cleaned = res.response.text().trim().replace(/^```json\s*/i, "").replace(/```$/i, "");
      const data = JSON.parse(cleaned);
      const finalUrgency = redFlags.length > 0 ? "red-flag" : (data.urgency || "normal");

      return {
        redFlags,
        urgency: finalUrgency,
        aiSummary: {
          chiefComplaint: data.chiefComplaint || symptoms[0]?.answer || "Not stated",
          associatedSymptoms: Array.isArray(data.associatedSymptoms) ? data.associatedSymptoms : [],
          duration: data.duration || symptoms[1]?.answer || "Not stated",
          pastHistory: Array.isArray(data.pastHistory) ? data.pastHistory : ["None reported"],
          currentMedication: Array.isArray(data.currentMedication) ? data.currentMedication : ["None reported"],
          measurements: sanitizedMeasurements.map((sm) => `${sm.label}: ${sm.status.value}`),
          oneLiner: data.oneLiner || `${patientInfo.age || ""}${patientInfo.sex ? patientInfo.sex[0] : ""} — ${symptoms[0]?.answer?.slice(0, 70) || ""}`,
          confidence: 0.92,
        },
      };
    } catch (err) {
      console.warn("[GeminiService] Summary generation fallback:", err.message);
    }
  }

  // Rule-based fallback summary
  const first = symptoms[0]?.answer || "Not stated";
  const duration = symptoms[1]?.answer || "Not stated";
  const associated = symptoms
    .slice(2)
    .map((s) => s.answer)
    .filter((a) => a && !/^none/i.test(a))
    .slice(0, 4);

  const meds = symptoms
    .filter((s) => /medicine/i.test(s.question))
    .map((s) => s.answer)
    .filter((a) => !/^no regular/i.test(a));

  const urgency = redFlags.length > 0 ? "red-flag" : associated.length > 2 ? "priority" : "normal";

  return {
    redFlags,
    urgency,
    aiSummary: {
      chiefComplaint: first,
      associatedSymptoms: associated.length ? associated : ["None volunteered"],
      duration,
      pastHistory: meds.length ? meds.map((m) => `Reported: ${m}`) : ["No chronic illness volunteered"],
      currentMedication: meds.length ? meds : ["None reported"],
      measurements: sanitizedMeasurements.map((sm) => `${sm.label}: ${sm.status.value}`),
      oneLiner: `${patientInfo.age || ""}${patientInfo.sex ? patientInfo.sex[0] : ""} — ${first.slice(0, 70)}`,
      confidence: 0.88,
    },
  };
}
